CREATE PROCEDURE GET_USER_DATA(IN CEDULA BIGINT(255))
BEGIN
	SET @IS_DIRECTOR = (
	SELECT COUNT(director.cedula) AS isDirector 
	FROM usuario
		CROSS JOIN director
		ON director.cedula = usuario.cedula
		WHERE usuario.cedula = CEDULA
	);

	SET @IS_ADMIN = (
		SELECT COUNT(administrador.cedula) AS isAdministrator 
		FROM usuario
			CROSS JOIN administrador
			ON administrador.cedula = usuario.cedula
			WHERE usuario.cedula = CEDULA
	);
	
	SET @IS_EMPLOYEE = (
		SELECT COUNT(empleado.cedula) AS isEmployee
		FROM usuario
			CROSS JOIN empleado
			ON empleado.cedula = usuario.cedula
			WHERE usuario.cedula = CEDULA
	);

	CREATE TEMPORARY TABLE FUNC_TEMP_TABLE_ROLE
		SELECT CEDULA AS cedula, @IS_DIRECTOR AS isDirector, @IS_ADMIN AS isAdministrator, @IS_EMPLOYEE AS isEmployee;

	SELECT * FROM usuario 
		CROSS JOIN FUNC_TEMP_TABLE_ROLE
		ON usuario.cedula = FUNC_TEMP_TABLE_ROLE.cedula
		WHERE cedula = CEDULA 
		LIMIT 1;

	DROP TEMPORARY TABLE FUNC_TEMP_TABLE_ROLE;
END $$

