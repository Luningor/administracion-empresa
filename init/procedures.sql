-- GET NEXT VALID DATE FROM RECURSIVE EVENT ID
CREATE FUNCTION GET_RECURRENT_EVENT_DATE(EVENT_ID INT)
RETURNS TIMESTAMP
BEGIN
	DECLARE CURR_DATE BIGINT(255) DEFAULT UNIX_TIMESTAMP(NOW());
	DECLARE BASE_DATE BIGINT(255) DEFAULT 0;
	DECLARE PERIOD BIGINT(255) DEFAULT 0;
	SET BASE_DATE = UNIX_TIMESTAMP((SELECT fecha FROM evento WHERE identificador = EVENT_ID LIMIT 1));
	SET PERIOD = (SELECT periodo FROM eventoperiodico WHERE identificadorEvento = EVENT_ID LIMIT 1);

	IF ISNULL(BASE_DATE) OR ISNULL(PERIOD) THEN
		RETURN NULL;
	END IF;

	-- IF THE BASE DATE IS OLDER THAN TODAY
	IF CURR_DATE > BASE_DATE THEN
		-- SLICE THE DIFFERENCE BETWEEN DATE AND TODAY IN (PERIOD)S, TAKE TODAY'S DATE, ADD A PERIOD, SUBSTRACT MODULUS AND TURN INTO A TIMESTAMP
		SET BASE_DATE = CURR_DATE + PERIOD - ((CURR_DATE - BASE_DATE) % PERIOD); 
	END IF;

	RETURN FROM_UNIXTIME(BASE_DATE);

END $$

-- GET VALUE OF PRODUCT ID IN GIVEN DATE
CREATE FUNCTION GET_PRODUCT_PRICE_ON_DATE(PRODUCT_ID INT, SPECIFIED_DATE TIMESTAMP)
RETURNS FLOAT(2)
BEGIN
	-- CURRENT PRICE
	DECLARE BASE_PRICE FLOAT(2);
	SET BASE_PRICE = (SELECT precio FROM producto WHERE id = PRODUCT_ID LIMIT 1);
	-- PRICE HISTORY FROM BEFORE SPECIFIED DATE (INCLUSIVE)
	CREATE TEMPORARY TABLE FUNC_TEMP_TABLE_PRICES SELECT * FROM historialPrecio WHERE id = PRODUCT_ID AND UNIX_TIMESTAMP(fechaCambio) <= UNIX_TIMESTAMP(SPECIFIED_DATE);

	-- GET *LATEST* DATED PRICE OR DEFAULT TO CURRENT PRICE
	IF (SELECT COUNT(precio) FROM FUNC_TEMP_TABLE_PRICES) > 0 THEN
		SET BASE_PRICE = (SELECT precio FROM FUNC_TEMP_TABLE_PRICES WHERE id = PRODUCT_ID ORDER BY fechaCambio DESC LIMIT 1);
	END IF;

	DROP TEMPORARY TABLE FUNC_TEMP_TABLE_PRICES;

	RETURN BASE_PRICE;
END $$

